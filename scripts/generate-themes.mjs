// Writes a source in src/<lang>/<name>/ for each Keiyoushi extension built on a theme this
// repository has (themes/), when what the extension changes is only settings the theme takes:
// selectors, its chapter mode, a date format, a rate limit. Extensions with code of their own
// are listed as skipped; port those by hand.
//
//   node scripts/generate-themes.mjs <keiyoushi extensions-source checkout> [--report]
//
// The checkout needs each extension's build.gradle.kts and Kotlin sources (a sparse checkout
// of src/*/*/build.gradle.kts and src/*/*/src/** is enough). Generated folders start with
// GENERATED_HEADER; the script rewrites those, removes the ones it no longer generates, and
// never touches anything else. Sites listed in scripts/theme-sites.json under "skip" (ones
// that fail `npm test`, say) aren't generated.

