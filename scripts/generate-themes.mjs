const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const keiyoushi = process.argv[2]
if (!keiyoushi || !existsSync(path.join(keiyoushi, "src"))) {
  console.error("usage: node scripts/generate-themes.mjs <keiyoushi extensions-source checkout> [--report]")
  process.exit(2)
}
const report = process.argv.includes("--report")
const settings = JSON.parse(readFileSync(path.join(root, "scripts", "theme-sites.json"), "utf8"))
const files = new Set(execFileSync("git", ["-C", keiyoushi, "ls-tree", "-r", "--name-only", "HEAD"], { encoding: "utf8", maxBuffer: 1 << 28 }).split("\n"))

const generated = new Map()
const skipped = []
for (const lang of readdirSync(path.join(keiyoushi, "src"))) {
  for (const name of readdirSync(path.join(keiyoushi, "src", lang))) {
    const folder = path.join(keiyoushi, "src", lang, name)
    const gradleFile = path.join(folder, "build.gradle.kts")
    if (!existsSync(gradleFile)) continue
    const gradle = readFileSync(gradleFile, "utf8")
    const themeName = /^\s*theme\s*=\s*"([^"]+)"/m.exec(gradle)?.[1]
    if (!themes[themeName]) continue
    const key = `${lang}/${name}`
    if (settings.skip?.[key]) { skipped.push([key, settings.skip[key]]); continue }
    const target = path.join(root, "src", lang, name)
    if (existsSync(path.join(target, "index.ts")) && !readFileSync(path.join(target, "index.ts"), "utf8").startsWith(GENERATED_HEADER)) {
      skipped.push([key, "ported by hand"])
      continue
    }
    try {
      generated.set(key, generate({ lang, name, folder, gradle, theme: themes[themeName], themeName }))
    } catch (error) {
      skipped.push([key, error.message])
    }
  }
}

// Remove what was generated before but isn't now; write the rest.
for (const lang of readdirSync(path.join(root, "src"))) {
  for (const name of readdirSync(path.join(root, "src", lang))) {
    const file = path.join(root, "src", lang, name, "index.ts")
    if (!generated.has(`${lang}/${name}`) && existsSync(file) && readFileSync(file, "utf8").startsWith(GENERATED_HEADER)) {
      rmSync(path.join(root, "src", lang, name), { recursive: true })
    }
  }
}
for (const [key, code] of generated) {
  mkdirSync(path.join(root, "src", key), { recursive: true })
  writeFileSync(path.join(root, "src", key, "index.ts"), code)
}

const reasons = new Map()
for (const [, reason] of skipped) reasons.set(reason.replace(/:.*/s, ""), (reasons.get(reason.replace(/:.*/s, "")) ?? 0) + 1)
console.log(`${generated.size} generated, ${skipped.length} skipped`)
for (const [reason, count] of [...reasons].sort((a, b) => b[1] - a[1]).slice(0, 15)) console.log(`  ${String(count).padStart(4)} ${reason}`)
if (report) for (const [key, reason] of skipped) console.log(`${key}\t${reason.replace(/\s+/g, " ").slice(0, 160)}`)

// MARK: One extension

function generate({ lang, name, folder, gradle, theme, themeName }) {
  const extension = parseGradle(gradle)
  const kotlin = kotlinSources(folder)
  const { base, members } = parseKotlin(kotlin, theme)
  const options = { ...theme.classes[base], ...members }
  const icon = files.has(`src/${lang}/${name}/res/mipmap-xhdpi/ic_launcher.png`)
    ? `https://cdn.jsdelivr.net/gh/keiyoushi/extensions-source@main/src/${lang}/${name}/res/mipmap-xhdpi/ic_launcher.png`
    : undefined
  delete options.rateLimit

  const sources = extension.sources.map((source) => {
    const sourceName = source.name ?? extension.name
    const info = {
      id: source.id ?? mihonSourceID(sourceName, source.lang, source.versionId ?? 1),
      name: sourceName,
      lang: source.lang,
      version: `${theme.version}.${extension.versionCode}`,
      baseUrl: source.baseUrl,
      ...(extension.nsfw ? { nsfw: true } : {}),
      ...(icon ? { icon } : {}),
      ...(members.rateLimit ? { rateLimits: [{ host: hostOf(source.baseUrl), ...members.rateLimit }] } : {}),
    }
    return { info, ...options }
  })

  const body = sources.length === 1
    ? `export default ${themeName}(${literal(sources[0], 0)})\n`
    : `export default [\n${sources.map((s) => `  ${themeName}(${literal(s, 1)}),`).join("\n")}\n]\n`
  return `${GENERATED_HEADER} from the Keiyoushi "${extension.name}" extension
// (${themeName} theme, versionCode ${extension.versionCode}):
// https://github.com/keiyoushi/extensions-source/tree/main/src/${lang}/${name}
// Licensed under the Apache License, Version 2.0. Regenerate it rather than edit it; to port
// it by hand instead, drop this header.

import { ${themeName} } from "../../../themes/${themeName}"

${body}`
}

function parseGradle(gradle) {
  const name = /^\s*name\s*=\s*"([^"]+)"/m.exec(gradle)?.[1]
  const versionCode = Number(/^\s*versionCode\s*=\s*(\d+)/m.exec(gradle)?.[1] ?? 0)
  const warning = /contentWarning\s*=\s*ContentWarning\.(\w+)/.exec(gradle)?.[1] ?? "SAFE"
  if (!name) throw new Error("no name in build.gradle.kts")

  const sources = []
  // listOf("en", "ko").forEach { source { lang = it … } }
  for (const loop of gradle.matchAll(/listOf\(([^)]*)\)\.forEach\s*\{([\s\S]*?source\s*\{[\s\S]*?\})\s*\}/g)) {
    const langs = [...loop[1].matchAll(/"([^"]+)"/g)].map((m) => m[1])
    const block = sourceBlock(loop[2])
    for (const lang of langs) sources.push({ ...block, lang })
  }
  if (sources.length === 0) {
    for (const match of gradle.matchAll(/\bsource\s*\{/g)) {
      const block = sourceBlock(balanced(gradle, match.index + match[0].length - 1))
      if (!block.lang) throw new Error("a source without a lang")
      sources.push(block)
    }
  }
  if (sources.length === 0) throw new Error("no source in build.gradle.kts")
  for (const source of sources) if (!source.baseUrl) throw new Error("a source without a baseUrl")
  return { name, versionCode, nsfw: warning !== "SAFE", sources }
}

function sourceBlock(block) {
  const get = (field) => new RegExp(`^\\s*${field}\\s*=\\s*"([^"]+)"`, "m").exec(block)?.[1]
  const lang = get("lang")
  const baseUrl = get("baseUrl") ?? /baseUrl\s*\{[\s\S]*?"(https?:[^"]+)"/.exec(block)?.[1]
  const id = /^\s*id\s*=\s*(\d+)L?/m.exec(block)?.[1]
  const versionId = /^\s*versionId\s*=\s*(\d+)/m.exec(block)?.[1]
  if (/\bit\b/.test(block.replace(/lang\s*=\s*it/, "")) && /=\s*it\b/.test(block.replace(/lang\s*=\s*it/, ""))) throw new Error("a source block that depends on its loop")
  return {
    ...(get("name") ? { name: get("name") } : {}),
    ...(lang ? { lang } : {}),
    baseUrl: baseUrl?.replace(/\/$/, ""),
    ...(id ? { id } : {}),
    ...(versionId ? { versionId: Number(versionId) } : {}),
  }
}

/** The text inside the braces that open at `start`. */
function balanced(text, start) {
  let depth = 0
  for (let i = start; i < text.length; i++) {
    if (text[i] === "{") depth++
    else if (text[i] === "}" && --depth === 0) return text.slice(start + 1, i)
  }
  throw new Error("unbalanced braces")
}

function kotlinSources(folder) {
  const found = []
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name)
      if (entry.isDirectory()) walk(full)
      else if (entry.name.endsWith(".kt")) found.push(readFileSync(full, "utf8"))
    }
  }
  if (existsSync(path.join(folder, "src"))) walk(path.join(folder, "src"))
  if (found.length === 0) throw new Error("no Kotlin source checked out")
  if (found.length > 1) throw new Error("more than one Kotlin file")
  return found[0]
}

// MARK: Kotlin

/** The class a site extends and the members it overrides, as theme options. */
function parseKotlin(source, theme) {
  const code = stripComments(source)
    .replace(/^\s*(package|import)\s.*$/gm, "")
    .replace(/@[A-Z]\w*(\([^)]*\))?/g, "")
  const declaration = /(?:abstract\s+|open\s+)?class\s+\w+(?:\s*\([^)]*\))?\s*:\s*(\w+)\s*\(\s*\)/.exec(code)
  if (!declaration) throw new Error(`extends something other than a theme class: ${code.trim().slice(0, 80)}`)
  const base = declaration[1]
  if (!theme.classes[base]) throw new Error(`extends ${base}`)
  const rest = code.slice(declaration.index + declaration[0].length).trim()
  if (code.slice(0, declaration.index).trim()) throw new Error(`code outside the class: ${code.slice(0, declaration.index).trim().slice(0, 80)}`)
  let body = ""
  if (rest.startsWith("{")) {
    body = balanced(rest, 0)
    if (rest.slice(body.length + 2).trim()) throw new Error(`code after the class: ${rest.slice(body.length + 2).trim().slice(0, 80)}`)
  } else if (rest) {
    throw new Error(`code after the class: ${rest.slice(0, 80)}`)
  }
  return { base, members: parseMembers(body, theme) }
}

function parseMembers(body, theme) {
  const members = {}
  let rest = body
  const string = String.raw`((?:"(?:[^"\\$]|\\.)*"|"""[\s\S]*?""")(?:\s*\+\s*(?:"(?:[^"\\$]|\\.)*"|"""[\s\S]*?"""))*)`
  const patterns = [
    // override val x = "…" / override val x: String = "…" / override val x get() = "…"
    [new RegExp(String.raw`^override\s+val\s+(\w+)(?:\s*:\s*String\??)?\s*(?:=|get\(\)\s*=)\s*${string}`), (m) => {
      if (!theme.strings.includes(m[1])) throw new Error(`overrides ${m[1]}`)
      members[m[1]] = kotlinString(m[2])
    }],
    // override fun x() = "…" / override fun x(): String = "…"
    [new RegExp(String.raw`^override\s+fun\s+(\w+)\(\)(?:\s*:\s*String\??)?\s*=\s*${string}`), (m) => {
      if (!theme.functions.includes(m[1])) throw new Error(`overrides ${m[1]}()`)
      members[m[1]] = kotlinString(m[2])
    }],
    [/^override\s+val\s+(\w+)(?:\s*:\s*Boolean)?\s*(?:=|get\(\)\s*=)\s*(true|false)\b/, (m) => {
      if (theme.ignoredBooleans.includes(m[1])) return
      if (m[1] === "supportsFilterFetching") { if (m[2] === "false") throw new Error("overrides supportsFilterFetching"); return }
      if (!theme.booleans.includes(m[1])) throw new Error(`overrides ${m[1]}`)
      members[m[1]] = m[2] === "true"
    }],
    [/^override\s+val\s+(\w+)(?:\s*:\s*Int)?\s*(?:=|get\(\)\s*=)\s*(\d+)\b/, (m) => {
      if (!theme.numbers.includes(m[1])) throw new Error(`overrides ${m[1]}`)
      members[m[1]] = Number(m[2])
    }],
    [/^override\s+val\s+(\w+)(?:\s*:\s*\w+)?\s*(?:=|get\(\)\s*=)\s*(\w+)\.(\w+)\b(?!\s*[.(])/, (m) => {
      if (theme.enums[m[1]] !== m[2]) throw new Error(`overrides ${m[1]}`)
      members[m[1]] = m[3]
    }],
    // override val chapterDateFormat = DateTimeFormatter.ofPattern("…", Locale…)
    [/^override\s+val\s+(\w+)(?:\s*:\s*DateTimeFormatter)?\s*(?:=|by\s+lazy\s*\{)\s*DateTimeFormatter\.ofPattern\(\s*"([^"]+)"\s*(?:,\s*(Locale(?:\.forLanguageTag)?\([^)]*\)|Locale\.[A-Z_]+))?\s*\)\s*\}?/, (m) => {
      if (m[1] !== theme.dateFormat) throw new Error(`overrides ${m[1]}`)
      members.chapterDateFormat = { pattern: m[2], locale: localeTag(m[3]) }
    }],
    // override fun OkHttpClient.Builder.configureClient() = rateLimit(2, 1.seconds) { … }
    [/^override\s+fun\s+OkHttpClient\.Builder\.configureClient\(\)\s*=\s*rateLimit\(\s*(\d+)\s*(?:,\s*(\d+)\.(seconds|milliseconds|minutes))?\s*\)(\s*\{[^{}]*\})?/, (m) => {
      const unit = { seconds: 1000, milliseconds: 1, minutes: 60000 }[m[3] ?? "seconds"]
      members.rateLimit = { permits: Number(m[1]), periodMs: Number(m[2] ?? 1) * unit }
    }],
  ]
  for (;;) {
    rest = rest.trim()
    if (!rest) return members
    const pattern = patterns.find(([regex]) => regex.test(rest))
    if (!pattern) throw new Error(`code of its own: ${rest.slice(0, 80)}`)
    const match = pattern[0].exec(rest)
    pattern[1](match)
    rest = rest.slice(match[0].length)
  }
}

function stripComments(code) {
  return code.replace(/"""[\s\S]*?"""|"(?:[^"\\]|\\.)*"|\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, (m) => m.startsWith("/") ? "" : m)
}

/** The value of a Kotlin string expression of literals joined with +. */
function kotlinString(expression) {
  let value = ""
  for (const part of expression.matchAll(/"""([\s\S]*?)"""|"((?:[^"\\]|\\.)*)"/g)) {
    if (part[1] !== undefined) {
      if (part[1].includes("$")) throw new Error("a string template")
      value += part[1]
    } else {
      value += part[2].replace(/\\(u[\da-fA-F]{4}|.)/g, (_, escape) => escape.length === 5 ? String.fromCharCode(parseInt(escape.slice(1), 16)) : ({ n: "\n", t: "\t", r: "\r" }[escape] ?? escape))
    }
  }
  return value
}

function localeTag(expression) {
  if (!expression) return "en"
  const constants = { US: "en-US", ENGLISH: "en", UK: "en-GB", ROOT: "en", FRENCH: "fr", FRANCE: "fr-FR", GERMAN: "de", ITALIAN: "it", JAPANESE: "ja", KOREAN: "ko", CHINESE: "zh", SIMPLIFIED_CHINESE: "zh-CN", TRADITIONAL_CHINESE: "zh-TW" }
  const constant = /^Locale\.([A-Z_]+)$/.exec(expression)?.[1]
  if (constant) return constants[constant] ?? "en"
  const parts = /"([^"]+)"(?:\s*,\s*"([^"]+)")?/.exec(expression)
  if (!parts) throw new Error(`a locale it can't read: ${expression}`)
  return parts[2] ? `${parts[1]}-${parts[2]}` : parts[1]
}

// MARK: Output

function literal(value, depth) {
  const pad = "  ".repeat(depth)
  if (Array.isArray(value)) return `[${value.map((v) => literal(v, depth)).join(", ")}]`
  if (value && typeof value === "object") {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined)
    const inline = `{ ${entries.map(([k, v]) => `${k}: ${literal(v, depth + 1)}`).join(", ")} }`
    if (pad.length + inline.length <= 100 && !inline.includes("\n")) return inline
    return `{\n${entries.map(([k, v]) => `${pad}  ${k}: ${literal(v, depth + 1)},`).join("\n")}\n${pad}}`
  }
  return JSON.stringify(value)
}

function hostOf(url) {
  return /^https?:\/\/([^/:]+)/.exec(url)?.[1] ?? url
}

/** Mihon's source ID: the first 8 bytes of MD5("<name lowercased>/<lang>/<versionId>"), sign bit cleared. */
function mihonSourceID(name, lang, versionID) {
  const digest = createHash("md5").update(`${name.toLowerCase()}/${lang}/${versionID}`).digest()
  return (digest.readBigUInt64BE(0) & 0x7fffffffffffffffn).toString()
}
