// Runs `npm test` for many built sources at once and reports which pass: popular, latest,
// details, chapters and pages all work and a page image downloads.
//
//   node scripts/test-sources.mjs [--generated] [--jobs 8] [--timeout 180] [name | id …]
//
// --generated tests the sources scripts/generate-themes.mjs wrote. Results go to
// dist/test-report.tsv (key, id, name, result, first failure) and the console.

import { execFileSync, spawn } from "node:child_process"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const args = process.argv.slice(2)
const option = (name, fallback) => {
  const index = args.indexOf(name)
  if (index < 0) return fallback
  const [value] = args.splice(index, 2).slice(1)
  return value
}
const jobs = Number(option("--jobs", 8))
const timeout = Number(option("--timeout", 180)) * 1000
const generatedOnly = args.includes("--generated")
const wanted = args.filter((arg) => !arg.startsWith("--")).map((arg) => arg.toLowerCase())

execFileSync("swift", ["build", "--package-path", "tester", "-c", "release"], { cwd: root, stdio: ["ignore", "ignore", "inherit"] })
const tester = path.join(root, "tester/.build/release/honya-test")
const index = JSON.parse(readFileSync(path.join(root, "dist/index.json"), "utf8"))

const keyOf = (source) => source.file.replace(/^sources\//, "").replace(/\.js$/, "").replace(".", "/")
const isGenerated = (key) => {
  const file = path.join(root, "src", key, "index.ts")
  return existsSync(file) && readFileSync(file, "utf8").startsWith("// Generated by scripts/generate-themes.mjs")
}
const sources = index.sources.filter((source) =>
  (!generatedOnly || isGenerated(keyOf(source))) &&
  (wanted.length === 0 || wanted.includes(source.id) || wanted.includes(source.name.toLowerCase()) || wanted.includes(`${source.name.toLowerCase()}/${source.lang}`)))
console.log(`Testing ${sources.length} sources, ${jobs} at a time`)

const results = []
let next = 0, done = 0
await Promise.all(Array.from({ length: Math.min(jobs, sources.length) }, async () => {
  while (next < sources.length) {
    const source = sources[next++]
    const result = await run(source)
    results.push(result)
    done++
    console.log(`${String(done).padStart(4)}/${sources.length} ${result.result.padEnd(7)} ${source.name} (${source.lang})${result.failure ? `: ${result.failure}` : ""}`)
  }
}))

results.sort((a, b) => a.key.localeCompare(b.key) || a.lang.localeCompare(b.lang))
writeFileSync(path.join(root, "dist/test-report.tsv"), results.map((r) => [r.key, r.id, r.name, r.lang, r.result, r.failure ?? ""].join("\t")).join("\n") + "\n")
const counts = Object.groupBy(results, (r) => r.result)
console.log(Object.entries(counts).map(([result, list]) => `${list.length} ${result}`).join(", ") + " → dist/test-report.tsv")

function run(source) {
  return new Promise((resolve) => {
    const child = spawn(tester, [path.join(root, "dist"), source.id], { cwd: root })
    let output = ""
    child.stdout.on("data", (data) => { output += data })
    child.stderr.on("data", (data) => { output += data })
    const timer = setTimeout(() => child.kill("SIGKILL"), timeout)
    child.on("close", (code, signal) => {
      clearTimeout(timer)
      const failure = /^✗ (.*)$/m.exec(output)?.[1]
      // An empty popular list or page list skips the steps after it, so passing also needs a
      // page image to have downloaded.
      const result = signal ? "TIMEOUT" : code === 0 && output.includes("✓ page image") ? "PASS" : "FAIL"
      const empty = ["pages", "chapters"].find((what) => new RegExp(`^\\s+0 ${what}\\b`, "m").test(output)) ??
        (/popular p1[^\n]*\n\s+0 manga\b/.test(output) ? "manga" : undefined)
      const reason = failure ?? (signal ? undefined : code === 0 ? `no ${empty ?? "page image"} to test` : output.trim().split("\n").pop())
      resolve({ key: keyOf(source), id: source.id, name: source.name, lang: source.lang, result, failure: result === "PASS" ? undefined : reason?.slice(0, 200) })
    })
  })
}
